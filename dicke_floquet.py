"""Floquet-Liouvillian spectrum and the micromotion geometric phase of the
periodically modulated open Dicke model.

Two questions are addressed here.

1. Late-time content of stroboscopic parity-odd signals.  The one-period map
   E = exp(pi L_off) exp(pi L_on) commutes with the parity superoperator.  At
   late times rho(mT) = rho_F + c mu_1^m r_1 + ..., where rho_F is the
   (parity-even) Floquet steady state and r_1 the slowest parity-odd mode.
   Every parity-odd functional F[rho] (magnetization, Im Z_Q, the paired
   contrast S, ...) is then F'[rho_F](r_1) c mu_1^m + o(|mu_1|^m).  All such
   signals share the decay rate -ln|mu_1| per period; they differ only by a
   constant prefactor.  ``floquet_spectrum`` computes mu_1 directly.

2. A physical closed loop.  The Floquet steady state is T periodic, so its
   micromotion t -> rho_F(t), 0 <= t <= T, is a closed loop of density
   matrices generated by the real dynamics (equivalently: the family of
   Floquet steady states obtained by winding the timing phase of the drive).
   Its kinematic mixed-state GP (Tong et al. 2004) needs no auxiliary
   generator.  Because rho_F(t) commutes with parity at every t, the
   amplitude splits exactly into parity sectors, Z_T = Z_even + Z_odd.  If
   rho_F = (rho_A + rho_B)/2 with rho_B = Pi rho_A Pi, orthogonal supports
   along the loop and E[rho_A] = rho_B (an ideal period-doubled pair), every
   even eigenvector |a> + Pi|a> has an odd partner |a> - Pi|a> of equal
   weight whose holonomy differs by exactly pi, so Z_even = -Z_odd.  The
   relative sector phase arg(Z_even / Z_odd) is a geometric counterpart of
   pi pairing, read from a parity-symmetric state in which every one-time
   order parameter vanishes.

Vectorization is column-major, as in QuTiP's operator_to_vector.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from typing import Any

for _thread_var in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_thread_var, "1")

import numpy as np
import qutip as qt
from scipy.optimize import linear_sum_assignment
from scipy.sparse.linalg import LinearOperator, eigs, expm_multiply


@dataclass
class DickeFloquetModel:
    atoms: int
    cutoff: int
    epsilon: float
    kappa: float
    coupling: float
    dim: int
    parity: np.ndarray          # +/-1 diagonal of Pi in the product basis
    parity_vec: np.ndarray      # +/-1 action of Pi . Pi on vec(rho)
    L_on: Any                   # sparse Liouvillians (csc)
    L_off: Any
    ops: dict                   # dense operators: n, jx, jy, jz
    sector_index: dict          # vec indices of the parity-even/odd superoperator sectors
    sector_L: dict              # {sector: (L_on, L_off)} restricted to that sector


def build_model(atoms: int = 2, cutoff: int = 24, epsilon: float = 0.01,
                kappa: float = 0.05, coupling: float = 1.0) -> DickeFloquetModel:
    """Same conventions as dicke_gp_scan.simulate_point."""
    j = atoms / 2.0
    spin_dim = atoms + 1
    dim = cutoff * spin_dim
    a = qt.tensor(qt.destroy(cutoff), qt.qeye(spin_dim))
    n = a.dag() * a
    jx = qt.tensor(qt.qeye(cutoff), qt.jmat(j, "x"))
    jy = qt.tensor(qt.qeye(cutoff), qt.jmat(j, "y"))
    jz = qt.tensor(qt.qeye(cutoff), qt.jmat(j, "z"))
    h_off = (1.0 - epsilon) * n + (1.0 + epsilon) * jz
    h_on = h_off + 2.0 * coupling / np.sqrt(atoms) * (a + a.dag()) * jx
    collapse = [np.sqrt(kappa) * a] if kappa else []
    L_on = qt.liouvillian(h_on, collapse).data.as_scipy().tocsc()
    L_off = qt.liouvillian(h_off, collapse).data.as_scipy().tocsc()
    # Pi = exp(i pi (n + Jz + j)); qutip jmat orders m = j, j-1, ..., -j.
    photon = np.repeat(np.arange(cutoff), spin_dim)
    spin_excitations = np.tile(np.arange(spin_dim)[::-1], cutoff)  # j + m
    parity = (-1.0) ** (photon + spin_excitations)
    parity_vec = np.outer(parity, parity).reshape(-1, order="F")
    ops = {"n": n.full(), "jx": jx.full(), "jy": jy.full(), "jz": jz.full()}
    # The Liouvillians commute with Pi . Pi, so they are block diagonal in the
    # two superoperator parity sectors; restricting halves every matvec.
    sector_index = {"even": np.flatnonzero(parity_vec > 0), "odd": np.flatnonzero(parity_vec < 0)}
    sector_L = {name: tuple(L[idx][:, idx].tocsc() for L in (L_on, L_off))
                for name, idx in sector_index.items()}
    return DickeFloquetModel(atoms, cutoff, epsilon, kappa, coupling, dim, parity,
                             parity_vec, L_on, L_off, ops, sector_index, sector_L)


def one_period(model: DickeFloquetModel, vec: np.ndarray) -> np.ndarray:
    """Coupling on for the first half period, off for the second (T = 2 pi)."""
    out = expm_multiply(np.pi * model.L_on, vec)
    return expm_multiply(np.pi * model.L_off, out)


def floquet_spectrum(model: DickeFloquetModel, sector: str, k: int = 4,
                     tol: float = 1e-10, seed: int = 1) -> tuple[np.ndarray, np.ndarray]:
    """Leading eigenvalues/modes of the one-period map in one parity sector.

    The map is applied with the sector-restricted Liouvillians, so modes of
    the other sector cannot enter the Krylov space.  Returned eigenvectors are
    embedded back into the full vec(rho) space.
    """
    idx = model.sector_index[sector]
    L_on, L_off = model.sector_L[sector]
    size = len(idx)
    operator = LinearOperator(
        (size, size), dtype=complex,
        matvec=lambda v: expm_multiply(np.pi * L_off, expm_multiply(np.pi * L_on, v)))
    rng = np.random.default_rng(seed)
    start = rng.normal(size=size) + 1j * rng.normal(size=size)
    values, vectors = eigs(operator, k=k, which="LM", v0=start, tol=tol,
                           ncv=max(2 * k + 8, 24), maxiter=5000)
    order = np.argsort(-np.abs(values))
    full = np.zeros((model.dim ** 2, k), dtype=complex)
    full[idx] = vectors[:, order]
    return values[order], full


def floquet_steady_state(model: DickeFloquetModel, tol: float = 1e-11) -> tuple[np.ndarray, complex]:
    """Return vec(rho_F) at the strobe t = 0 and the even-sector eigenvalue found."""
    values, vectors = floquet_spectrum(model, "even", k=2, tol=tol)
    vec = vectors[:, 0]
    rho = vec.reshape((model.dim, model.dim), order="F")
    rho = rho / np.trace(rho)
    rho = 0.5 * (rho + rho.conj().T)
    return rho.reshape(-1, order="F"), values[0]


def _sector_indices(parity: np.ndarray) -> dict[str, np.ndarray]:
    return {"even": np.flatnonzero(parity > 0), "odd": np.flatnonzero(parity < 0)}


def micromotion_gp(model: DickeFloquetModel, rho_vec: np.ndarray, steps_per_half: int = 800,
                   weight_floor: float = 1e-9) -> dict[str, Any]:
    """Kinematic GP of the closed loop t -> rho_F(t), 0 <= t <= T, by parity sector.

    Eigenvectors are followed by maximal-overlap assignment inside each parity
    block at every time step; the discrete parallel-transport product is the
    same estimator used in test_gp_geometry.  Eigenvectors whose weight is
    below ``weight_floor`` at t=0 are not tracked; their total weight is
    returned as an error bound on |Z|.  Each tracked vector contributes
        lambda_k(0) <psi_k(0)|psi_k(T)> prod_i <psi_k(t_{i+1})|psi_k(t_i)>/|.|
    which equals lambda_k exp(i gamma_k) for a closed loop.
    """
    even_idx = model.sector_index["even"]
    if np.linalg.norm(rho_vec[model.sector_index["odd"]]) > 1e-10:
        raise ValueError("micromotion_gp expects a parity-symmetric state")
    grids = []
    current_even = rho_vec[even_idx]
    for generator in model.sector_L["even"]:
        grids.append(expm_multiply(generator, current_even, start=0.0, stop=np.pi,
                                   num=steps_per_half + 1, endpoint=True))
        current_even = grids[-1][-1]
    # Concatenate, dropping the duplicated switching instant, and embed.
    reduced = np.concatenate([grids[0], grids[1][1:]], axis=0)
    path = np.zeros((len(reduced), model.dim ** 2), dtype=complex)
    path[:, even_idx] = reduced
    closure_error = float(np.linalg.norm(path[-1] - path[0]))
    matrices = (vec.reshape((model.dim, model.dim), order="F") for vec in path)
    result = sector_loop_amplitudes(matrices, model.parity, weight_floor=weight_floor)
    result.update({"closure_error": closure_error, "steps": len(path) - 1})
    return result


def sector_loop_amplitudes(path, parity: np.ndarray, *, weight_floor: float = 1e-9,
                           top: int = 6) -> dict[str, Any]:
    """Parity-resolved kinematic GP of a closed path of density matrices.

    ``path`` yields dense density matrices rho(t_0), ..., rho(t_M) with
    rho(t_M) = rho(t_0); every rho must commute with the diagonal parity
    ``parity`` (+/-1 entries).  Inside each parity block, eigenvectors are
    followed by maximal-overlap assignment and transported with the discrete
    estimator of test_gp_geometry.  Each tracked vector contributes
        lambda_k(0) <psi_k(0)|psi_k(T)> prod_i <psi_k(t_{i+1})|psi_k(t_i)>/|.|
    i.e. lambda_k exp(i gamma_k) for a closed loop.  Vectors with weight below
    ``weight_floor`` at t_0 are not tracked; their weight is reported.
    The ``top`` heaviest (weight, holonomy phase) pairs of each sector are
    returned for pair-resolved checks.
    """
    sectors = _sector_indices(parity)
    iterator = iter(path)
    first = next(iterator)
    state = {}
    for name, idx in sectors.items():
        block = first[np.ix_(idx, idx)]
        values0, vectors0 = np.linalg.eigh(0.5 * (block + block.conj().T))
        state[name] = dict(values0=values0, vectors0=vectors0, current=vectors0,
                           keep=np.flatnonzero(values0 > weight_floor),
                           transport=np.ones(len(values0), dtype=complex),
                           min_overlap=1.0, min_gap=np.inf)
    steps = 0
    for rho in iterator:
        steps += 1
        for name, idx in sectors.items():
            st = state[name]
            block = rho[np.ix_(idx, idx)]
            values, vectors = np.linalg.eigh(0.5 * (block + block.conj().T))
            overlap = st["current"].conj().T @ vectors       # <old_k | new_l>
            rows, cols = linear_sum_assignment(-np.abs(overlap))
            assigned = np.empty(len(values), dtype=int)
            assigned[rows] = cols
            step = overlap[np.arange(len(values)), assigned]
            st["min_overlap"] = min(st["min_overlap"], float(np.min(np.abs(step[st["keep"]]))))
            st["transport"] *= np.conj(step) / np.maximum(np.abs(step), 1e-300)
            st["current"] = vectors[:, assigned]
            if len(values) > 1:
                ordered = np.sort(values)
                tracked = values[assigned[st["keep"]]]
                pos = np.searchsorted(ordered, tracked)
                left = np.where(pos > 0, tracked - ordered[np.clip(pos - 1, 0, None)], np.inf)
                right = np.where(pos < len(values) - 1,
                                 ordered[np.clip(pos + 1, None, len(values) - 1)] - tracked, np.inf)
                st["min_gap"] = min(st["min_gap"], float(np.min(np.minimum(np.abs(left), np.abs(right)))))
    if steps == 0:
        raise ValueError("path must contain at least two density matrices")

    result: dict[str, Any] = {}
    phasors: dict[str, np.ndarray] = {}
    weights: dict[str, np.ndarray] = {}
    for name, st in state.items():
        keep, values0 = st["keep"], st["values0"]
        closing = np.einsum("ik,ik->k", st["vectors0"].conj(), st["current"])  # <psi_k(0)|psi_k(T)>
        factor = closing * st["transport"]
        phasors[name] = values0[keep] * factor[keep] / np.maximum(np.abs(factor[keep]), 1e-300)
        weights[name] = values0[keep]
        order = np.argsort(-weights[name])[:top]
        result[f"top_{name}"] = [[float(weights[name][i]), float(np.angle(phasors[name][i]))] for i in order]
        result[f"untracked_weight_{name}"] = float(values0[values0 <= weight_floor].clip(0).sum())
        result[f"min_step_overlap_{name}"] = st["min_overlap"]
        result[f"min_eigen_gap_{name}"] = st["min_gap"]
        result[f"min_closure_overlap_{name}"] = float(np.min(np.abs(closing[keep]))) if len(keep) else 1.0

    Z_even, Z_odd = phasors["even"].sum(), phasors["odd"].sum()
    # Doubled loop (traverse the same path twice): each phasor squared.
    Z2_even = (weights["even"] * (phasors["even"] / weights["even"]) ** 2).sum()
    Z2_odd = (weights["odd"] * (phasors["odd"] / weights["odd"]) ** 2).sum()
    result.update({
        "Z_even": complex(Z_even), "Z_odd": complex(Z_odd), "Z_T": complex(Z_even + Z_odd),
        "Z_2T": complex(Z2_even + Z2_odd),
        "weight_even": float(weights["even"].sum()), "weight_odd": float(weights["odd"].sum()),
        "relative_sector_phase": float(np.angle(Z_even * np.conj(Z_odd))),
        "pi_pairing": float(-np.real(Z_even * np.conj(Z_odd)) / max(abs(Z_even) * abs(Z_odd), 1e-300)),
        "phasors_even": phasors["even"], "phasors_odd": phasors["odd"],
    })
    return result


def strobe_observables(model: DickeFloquetModel, rho_vec: np.ndarray) -> dict[str, float]:
    rho = rho_vec.reshape((model.dim, model.dim), order="F")
    j = model.atoms / 2.0
    return {
        "nbar": float(np.real(np.trace(model.ops["n"] @ rho))),
        "jz_over_j": float(np.real(np.trace(model.ops["jz"] @ rho)) / j),
        "sigma_x": float(np.real(np.trace(model.ops["jx"] @ rho)) / j),
        "parity_odd_norm": float(np.linalg.norm(0.5 * (rho_vec - model.parity_vec * rho_vec))),
    }
